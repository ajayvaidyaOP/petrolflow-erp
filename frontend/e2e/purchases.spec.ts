test('purchase orders convert once into a separate traceable draft with no early posting', async ({ request }) => {
  const me=await session(request),stationId=me.stations[0].id;
  const opts=(await (await request.get(`/api/v1/purchases/options?stationId=${stationId}`)).json()).data;
  const date=new Date(Date.now()+330*60000).toISOString().slice(0,10);
  const payload={stationId,supplierId:opts.suppliers[0].id,invoiceNumber:`PO-${Date.now()}`,invoiceDate:date,dueDate:date,lines:[{tankId:opts.tanks[0].id,quantityLitres:'10',ratePerLitre:'100'}]};
  const balance=async()=>Number((await (await request.get(`/api/v1/finance/supplier-ledger?supplierId=${payload.supplierId}&stationId=${stationId}`)).json()).data.closingBalance);
  const stock=async()=>(await (await request.get(`/api/v1/inventory/stock?stationId=${stationId}`)).json()).data.tanks;
  const opening=await balance(),before=await stock();
  const created=await request.post('/api/v1/purchase-orders',{data:payload});expect(created.status()).toBe(201);
  const order=(await created.json()).data.id;
  expect((await request.post(`/api/v1/purchases/${order}/receive`,{data:{}})).status()).toBe(409);
  const orders=(await (await request.get(`/api/v1/purchases?stationId=${stationId}&documentType=ORDER&search=${payload.invoiceNumber}`)).json()).data;
  expect(orders).toHaveLength(1);expect(orders[0].documentType).toBe('ORDER');
  const conversion={invoiceNumber:`SUP-${Date.now()}`,invoiceDate:date,dueDate:date};
  const converted=await request.post(`/api/v1/purchases/${order}/convert-order`,{data:conversion});expect(converted.status()).toBe(201);
  const id=(await converted.json()).data.id;expect(id).not.toBe(order);
  expect((await request.post(`/api/v1/purchases/${order}/convert-order`,{data:conversion})).status()).toBe(409);
  const detail=(await (await request.get(`/api/v1/purchases/${id}`)).json()).data;
  expect(detail.status).toBe('DRAFT');expect(detail.sourceOrderId).toBe(order);expect(detail.lines).toHaveLength(1);expect(Number(detail.totalAmount)).toBe(1000);
  const source=(await (await request.get(`/api/v1/purchases/${order}`)).json()).data;
  expect(source.status).toBe('CONVERTED');expect(source.convertedInvoiceId).toBe(id);
  expect(await balance()).toBe(opening);expect(await stock()).toEqual(before);
  expect((await request.post(`/api/v1/purchases/${order}/cancel`,{data:{reason:'Cannot cancel converted'}})).status()).toBe(409);
  expect((await request.post(`/api/v1/purchases/${id}/receive`,{data:{}})).status()).toBe(200);
  expect(await balance()).toBeCloseTo(opening+1000,2);
});

