test('draft editing is versioned and cancellation never moves stock', async ({ request }) => {
  const me = await session(request);
  const stationId = me.stations[0].id;
  const options = (await (await request.get(`/api/v1/purchases/options?stationId=${stationId}`)).json()).data;
  const today = new Date(Date.now() + 330 * 60000).toISOString().slice(0, 10);
  const payload = { stationId, supplierId: options.suppliers[0].id, invoiceNumber: `EDIT-${Date.now()}`, invoiceDate: today, dueDate: today, lines: [{ tankId: options.tanks[0].id, quantityLitres: '10', ratePerLitre: '100' }] };
  const stock = async () => (await (await request.get(`/api/v1/inventory/stock?stationId=${stationId}`)).json()).data.tanks;
  const before = await stock();
  const created = await request.post('/api/v1/purchases', { data: payload });
  expect(created.status()).toBe(201);
  const id = (await created.json()).data.id;
  const edit = { ...payload, revision: 1, lines: [{ ...payload.lines[0], quantityLitres: '25' }] };
  expect((await request.post(`/api/v1/purchases/${id}/edit`, { data: edit })).status()).toBe(201);
  expect((await request.post(`/api/v1/purchases/${id}/edit`, { data: edit })).status()).toBe(409);
  const detail = (await (await request.get(`/api/v1/purchases/${id}`)).json()).data;
  expect(Number(detail.totalAmount)).toBe(2500);
  expect(detail.revision).toBe(2);
  expect(detail.lines).toHaveLength(1);
  const bad = { ...edit, revision: 2, lines: [{ ...edit.lines[0], tankId: 'missing' }] };
  expect((await request.post(`/api/v1/purchases/${id}/edit`, { data: bad })).status()).toBe(422);
  expect(Number((await (await request.get(`/api/v1/purchases/${id}`)).json()).data.totalAmount)).toBe(2500);
  expect((await request.post(`/api/v1/purchases/${id}/cancel`, { data: { reason: 'x' } })).status()).toBe(422);
  expect((await request.post(`/api/v1/purchases/${id}/cancel`, { data: { reason: 'Duplicate supplier draft' } })).status()).toBe(200);
  expect((await request.post(`/api/v1/purchases/${id}/receive`, { data: {} })).status()).toBe(409);
  expect((await request.post(`/api/v1/purchases/${id}/edit`, { data: { ...edit, revision: 3 } })).status()).toBe(409);
  expect(await stock()).toEqual(before);
});

test('partial quantities reconcile cents and reject overposting and concurrent duplicates', async ({ request }) => {
  const me = await session(request), stationId = me.stations[0].id;
  const opts = (await (await request.get(`/api/v1/purchases/options?stationId=${stationId}`)).json()).data;
  const date = new Date(Date.now()+330*60000).toISOString().slice(0,10);
  const data = { stationId, supplierId: opts.suppliers[0].id, invoiceNumber: `PART-${Date.now()}`, invoiceDate: date, dueDate: date, discountAmount:'1',freightAmount:'2',taxAmount:'3',lines:[{tankId:opts.tanks[0].id,quantityLitres:'3',ratePerLitre:'33.333'},{tankId:opts.tanks[1].id,quantityLitres:'2',ratePerLitre:'25'}] };
  const created = await request.post('/api/v1/purchases',{data});
  expect(created.status()).toBe(201);
  const id = (await created.json()).data.id;
  const detail = async () => (await (await request.get(`/api/v1/purchases/${id}`)).json()).data;
  const draft = await detail();
  const first = draft.lines.find((l: {tankId:string})=>l.tankId===opts.tanks[0].id);
  const second = draft.lines.find((l: {tankId:string})=>l.tankId===opts.tanks[1].id);
  const balance = async () => Number((await (await request.get(`/api/v1/finance/supplier-ledger?supplierId=${data.supplierId}&stationId=${stationId}`)).json()).data.closingBalance);
  const opening = await balance();
  const one = {lines:[{lineId:first.id,quantityLitres:'1'}]};
  const headers = {'Idempotency-Key':`partial-${id}`};
  const receipt = await request.post(`/api/v1/purchases/${id}/receive`,{data:one,headers});
  expect(receipt.status()).toBe(200);
  expect((await receipt.json()).data.amount).toBe('34.22');
  expect((await request.post(`/api/v1/purchases/${id}/receive`,{data:one,headers})).status()).toBe(200);
  expect((await detail()).events).toHaveLength(1);
  expect((await detail()).status).toBe('PARTIAL_RECEIVED');
  expect(await balance()).toBeCloseTo(opening+34.22,2);
  expect((await request.post(`/api/v1/purchases/${id}/return`,{data:{...one,reason:'Before completion'}})).status()).toBe(409);
  for (const lines of [[{lineId:first.id,quantityLitres:'3'}],[{lineId:'missing',quantityLitres:'1'}],[one.lines[0],one.lines[0]]]) {
    expect((await request.post(`/api/v1/purchases/${id}/receive`,{data:{lines}})).status()).toBe(422);
  }
  const concurrent = await Promise.all([1,2].map(()=>request.post(`/api/v1/purchases/${id}/receive`,{data:{lines:[{lineId:first.id,quantityLitres:'2'}]}})));
  expect(concurrent.map(r=>r.status()).sort()).toEqual([200,422]);
  expect((await request.post(`/api/v1/purchases/${id}/receive`,{data:{lines:[{lineId:second.id,quantityLitres:'2'}]}})).status()).toBe(200);
  expect(await balance()).toBeCloseTo(opening+154,2);
  expect((await detail()).status).toBe('RECEIVED');
  expect((await request.post(`/api/v1/purchases/${id}/return`,{data:{...one,reason:'One litre quality issue'}})).status()).toBe(200);
  expect((await detail()).status).toBe('PARTIAL_RETURNED');
  expect(await balance()).toBeCloseTo(opening+119.78,2);
  expect((await request.post(`/api/v1/purchases/${id}/return`,{data:{lines:[{lineId:first.id,quantityLitres:'3'}],reason:'Excessive return request'}})).status()).toBe(422);
  expect((await request.post(`/api/v1/purchases/${id}/return`,{data:{reason:'All remaining fuel returned'}})).status()).toBe(200);
  expect(await balance()).toBeCloseTo(opening,2);
  const final = await detail(); expect(final.status).toBe('RETURNED'); expect(final.events).toHaveLength(5);
  for (const line of final.lines) expect(Number(line.receivedLitres)).toBe(Number(line.returnedLitres));
  const dsr = (await (await request.get(`/api/v1/reports/dsr?stationId=${stationId}&date=${date}`)).json()).data;
  const entries = dsr.deliveries.filter((r:{invoiceNumber:string})=>r.invoiceNumber===data.invoiceNumber);
  expect(entries).toHaveLength(5);
  expect(entries.reduce((sum:number,row:{totalAmount:string})=>sum+Number(row.totalAmount),0)).toBeCloseTo(0,2);
});

