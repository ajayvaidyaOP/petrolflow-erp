test('multi-line purchase posts stock/payables once and a full return offsets both', async ({ request }) => {
  const me = await session(request);
  const stationId = me.stations[0].id;
  const suppliers = (await (await request.get('/api/v1/catalog/suppliers')).json()).data;
  const supplierId = suppliers[0].id;
  const stock = async () => (await (await request.get(`/api/v1/inventory/stock?stationId=${stationId}`)).json()).data;
  const before = await stock();
  const tanks = before.tanks;
  const balance = async () => (await (await request.get(`/api/v1/finance/supplier-ledger?supplierId=${supplierId}&stationId=${stationId}`)).json()).data.closingBalance;
  const oldBalance = Number(await balance());
  const today = new Date(Date.now() + 330 * 60000).toISOString().slice(0, 10);
  const payload = { stationId, supplierId, invoiceNumber: `MULTI-${Date.now()}`, invoiceDate: today, dueDate: today, discountAmount: '2', freightAmount: '3', taxAmount: '4', lines: tanks.slice(0, 2).map((t: { id: string }) => ({ tankId: t.id, quantityLitres: '10', ratePerLitre: '100' })) };
  const created = await request.post('/api/v1/purchases', { data: payload });
  expect(created.status()).toBe(201);
  const invalidPrice = { ...payload, invoiceNumber: `NEG-${Date.now()}`, lines: [{ ...payload.lines[0], ratePerLitre: '-1' }] };
  expect((await request.post('/api/v1/purchases', { data: invalidPrice })).status()).toBe(422);
  expect((await request.post('/api/v1/purchases', { data: { ...payload, invoiceNumber: `DATE-${Date.now()}`, dueDate: '2020-01-01' } })).status()).toBe(422);
  const id = (await created.json()).data.id;
  expect(Number(await balance())).toBe(oldBalance);
  const detail = (await (await request.get(`/api/v1/purchases/${id}`)).json()).data;
  expect(detail.lines).toHaveLength(2);
  expect(Number(detail.totalAmount)).toBe(2005);
  expect((await request.post('/api/v1/purchases', { data: payload })).status()).toBe(409);
  expect((await request.post(`/api/v1/purchases/${id}/receive`, { data: {} })).status()).toBe(200);
  expect((await request.post(`/api/v1/purchases/${id}/receive`, { data: {} })).status()).toBe(409);
  expect(Number(await balance())).toBeCloseTo(oldBalance + 2005, 2);
  const after = await stock();
  for (const tank of tanks.slice(0, 2)) expect(Number(after.tanks.find((t: { id: string }) => t.id === tank.id).bookStockLitres)).toBeCloseTo(Number(tank.bookStockLitres) + 10, 3);
  // A failed return must roll back every earlier line and leave the payable unchanged.
  const depleted = after.tanks.find((t: { id: string }) => t.id === tanks[1].id);
  expect((await request.post('/api/v1/inventory/adjustments', { data: { tankId: depleted.id, quantityLitres: String(-Number(depleted.bookStockLitres)), reason: 'Regression stock isolation' } })).ok()).toBeTruthy();
  expect((await request.post(`/api/v1/purchases/${id}/return`, { data: { reason: 'Wrong fuel delivery' } })).status()).toBe(409);
  expect(Number(await balance())).toBeCloseTo(oldBalance + 2005, 2);
  const failedReturnStock = await stock();
  expect(Number(failedReturnStock.tanks.find((t: { id: string }) => t.id === tanks[0].id).bookStockLitres)).toBeCloseTo(Number(tanks[0].bookStockLitres) + 10, 3);
  expect((await request.post('/api/v1/inventory/adjustments', { data: { tankId: depleted.id, quantityLitres: depleted.bookStockLitres, reason: 'Restore regression isolation' } })).ok()).toBeTruthy();
  expect((await request.post(`/api/v1/purchases/${id}/return`, { data: { reason: 'Wrong fuel delivery' } })).status()).toBe(200);
  expect((await request.post(`/api/v1/purchases/${id}/return`, { data: { reason: 'Wrong fuel delivery' } })).status()).toBe(409);
  expect(Number(await balance())).toBeCloseTo(oldBalance, 2);
  const restored = await stock();
  for (const tank of tanks.slice(0, 2)) expect(Number(restored.tanks.find((t: { id: string }) => t.id === tank.id).bookStockLitres)).toBeCloseTo(Number(tank.bookStockLitres), 3);
  const invalid = { ...payload, invoiceNumber: `BAD-${Date.now()}`, lines: [...payload.lines, { tankId: 'missing', quantityLitres: '10', ratePerLitre: '100' }] };
  expect((await request.post('/api/v1/purchases', { data: invalid })).status()).toBe(422);
  const list = (await (await request.get(`/api/v1/purchases?stationId=${stationId}&search=${invalid.invoiceNumber}`)).json()).data;
  expect(list).toHaveLength(0);
});

